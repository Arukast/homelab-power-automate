#!/bin/sh
# =============================================================================
# OpenWrt Homelab Power Orchestrator Shared Library
# File: /usr/bin/components/lib.sh
#
# Sourced by components/common_init.sh, so every consumer (power proxy daemon,
# wake listeners, telegram bot, config sync, installer helpers) gets the same
# helpers and configuration path constants.
#
# POSIX sh only (BusyBox ash): no eval, no sed, no bashisms, no extra deps.
# =============================================================================

# --- Canonical configuration paths -------------------------------------------
# ROUTER_CONF: configuration generated by the OpenWrt installer
# MSG_CONF:    notification message templates
# PVE_CONF:    configuration pushed to / consumed on the Proxmox host
export ROUTER_CONF="/etc/power_homelab.conf"
export MSG_CONF="/etc/messages_homelab.conf"
export PVE_CONF="/etc/homelab_power.conf"

# Thin syslog wrapper (BusyBox logger) for errors raised by shared helpers.
log_router() {
    logger -t homelab-power "$1"
}

# trim: read stdin, print the text with leading/trailing whitespace removed.
trim() {
    _trim_text=$(cat)

    # Strip leading whitespace
    while case "$_trim_text" in
        [[:space:]]*) true ;;
        *) false ;;
    esac
    do
        _trim_text="${_trim_text#?}"
    done

    # Strip trailing whitespace
    while case "$_trim_text" in
        *[[:space:]]) true ;;
        *) false ;;
    esac
    do
        _trim_text="${_trim_text%?}"
    done

    printf '%s\n' "$_trim_text"
}

# render_msg <template>: print <template> with the notification placeholder
# tokens replaced by the CURRENT values of the calling shell's variables.
# Pure parameter expansion: no eval, no sed, no subshell.
# Supported tokens: $arg1 $arg2 $arg3 $arg4 $HOST_MAC $GUEST_NAME $VMID
#                   $USER_ID $PORT_RAW $GUEST_IP
render_msg() {
    _render_out="$1"

    _render_out="${_render_out//\$arg1/${arg1}}"
    _render_out="${_render_out//\$arg2/${arg2}}"
    _render_out="${_render_out//\$arg3/${arg3}}"
    _render_out="${_render_out//\$arg4/${arg4}}"
    _render_out="${_render_out//\$HOST_MAC/${HOST_MAC}}"
    _render_out="${_render_out//\$GUEST_NAME/${GUEST_NAME}}"
    _render_out="${_render_out//\$VMID/${VMID}}"
    _render_out="${_render_out//\$USER_ID/${USER_ID}}"
    _render_out="${_render_out//\$PORT_RAW/${PORT_RAW}}"
    _render_out="${_render_out//\$GUEST_IP/${GUEST_IP}}"

    printf '%s\n' "$_render_out"
}

# source_required <path>: source the file, or fail loudly.
# A missing/renamed component must never silently leave a daemon running with
# only half of its functions defined.
source_required() {
    _source_path="$1"

    if [ -f "$_source_path" ]; then
        . "$_source_path"
    else
        echo "ERROR: required component '$_source_path' not found. Aborting." >&2
        log_router "FATAL: required component '$_source_path' not found."
        exit 1
    fi
}

# Internal: perform one Telegram API call.
# Usage: _tg_api_call <method> <chat_id> <text> <markup> <message_id> <parse_mode>
# Any empty optional argument is simply omitted from the request.
_tg_api_call() {
    _api_url="https://api.telegram.org/bot${BOT_TOKEN}/$1"

    # shellcheck disable=SC2086 # the ${x:+...} expansions are pre-split into
    # exactly two single-word parameters each (no user data, no spaces).
    if [ -n "$4" ]; then
        curl -s --connect-timeout 3 --max-time 10 -X POST "$_api_url" \
            --data-urlencode "chat_id=$2" \
            ${5:+--data-urlencode message_id=$5} \
            --data-urlencode "text=$3" \
            ${6:+--data-urlencode parse_mode=Markdown} \
            --data-urlencode "reply_markup=$4"
    else
        curl -s --connect-timeout 3 --max-time 10 -X POST "$_api_url" \
            --data-urlencode "chat_id=$2" \
            ${5:+--data-urlencode message_id=$5} \
            --data-urlencode "text=$3" \
            ${6:+--data-urlencode parse_mode=Markdown}
    fi
}

# tg_send <chat_id> <text> [markup] [message_id]
# Uses editMessageText when a message_id is given (in-place menu updates),
# sendMessage otherwise. Markdown is attempted first and retried without
# parse_mode, because Telegram rejects the whole message (HTTP 400) when the
# text contains unbalanced Markdown entities.
tg_send() {
    _tg_chat="$1"
    _tg_text="$2"
    _tg_markup="$3"
    _tg_msg_id="$4"

    if [ -z "$BOT_TOKEN" ] || [ "$BOT_TOKEN" = "YOUR_TELEGRAM_BOT_TOKEN" ]; then
        log_router "Telegram notification skipped: BOT_TOKEN is not configured."
        return 1
    fi

    if [ -n "$_tg_msg_id" ]; then
        _tg_method="editMessageText"
    else
        _tg_method="sendMessage"
    fi

    # Inline keyboards are built from heredocs; collapse them onto a single line
    # so they survive URL encoding.
    _tg_markup_inline=$(printf '%s' "$_tg_markup" | tr -d '\n')

    _tg_resp=$(_tg_api_call "$_tg_method" "$_tg_chat" "$_tg_text" "$_tg_markup_inline" "$_tg_msg_id" "Markdown")

    if ! printf '%s' "$_tg_resp" | grep -q '"ok":true'; then
        _tg_api_call "$_tg_method" "$_tg_chat" "$_tg_text" "$_tg_markup_inline" "$_tg_msg_id" "" >/dev/null
    fi

    return 0
}
